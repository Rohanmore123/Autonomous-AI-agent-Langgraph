async def _get_or_create_conversation(
    conversation_id: str | None,
    user_id: str,
    agent_type: str,
    db: AsyncSession,
) -> Conversation:
    if conversation_id:
        result = await db.execute(
            select(Conversation)
            .where(Conversation.id == conversation_id)
            .where(Conversation.user_id == user_id)
        )
        conv = result.scalar_one_or_none()
        if not conv:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Conversation not found",
            )
        return conv

    # Create new conversation
    conv = Conversation(
        user_id=user_id,
        agent_type=agent_type,
        title="New conversation",
    )
    db.add(conv)
    await db.flush()
    return conv


async def _save_messages(
    conversation: Conversation,
    user_content: str,
    assistant_content: str,
    llm_resp: LLMResponse,
    sources: list,
    tool_calls: list,
    db: AsyncSession,
) -> Message:
    """Write user + assistant messages to DB. Returns assistant message."""
    # User message
    db.add(Message(
        conversation_id=conversation.id,
        role="user",
        content=user_content,
    ))

    # Assistant message
    assistant_msg = Message(
        conversation_id=conversation.id,
        role="assistant",
        content=assistant_content,
        tokens_used=llm_resp.input_tokens + llm_resp.output_tokens,
        latency_ms=llm_resp.latency_ms,
        model=llm_resp.model,
        provider=llm_resp.provider,
        sources=[
            {"document_id": s.document_id, "filename": s.filename,
             "content": s.content[:500], "score": s.score}
            for s in sources
        ],
        tool_calls=tool_calls,
    )
    db.add(assistant_msg)

    # Update conversation stats
    conversation.total_tokens += llm_resp.input_tokens + llm_resp.output_tokens
    conversation.total_cost_usd += llm_resp.cost_usd
    conversation.model_used = llm_resp.model

    await db.flush()
    return assistant_msg


async def _log_agent_run(
    user_id: str,
    conversation_id: str,
    agent_type: str,
    llm_resp: LLMResponse,
    tool_calls: list,
    success: bool,
    db: AsyncSession,
    error_type: str | None = None,
) -> None:
    """Write an AgentRun telemetry record."""
    db.add(AgentRun(
        user_id=user_id,
        conversation_id=conversation_id,
        agent_type=agent_type,
        input_tokens=llm_resp.input_tokens,
        output_tokens=llm_resp.output_tokens,
        latency_ms=llm_resp.latency_ms,
        provider_used=llm_resp.provider,
        model_used=llm_resp.model,
        was_cached=llm_resp.was_cached,
        used_fallback=llm_resp.used_fallback,
        retry_count=llm_resp.retry_count,
        success=success,
        error_type=error_type,
        tool_calls_made=tool_calls,
        cost_usd=llm_resp.cost_usd,
    ))


