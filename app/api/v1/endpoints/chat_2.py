@router.post(
    "",
    response_model=APIResponse[ChatResponse],
    summary="Send a message to the AI platform",
)
async def chat(
    body: ChatRequest,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db_session),
) -> APIResponse[ChatResponse]:
    """
    Unified chat endpoint. Routes to:
      • RAG Agent     — questions answered from uploaded documents
      • Gmail Agent   — email management
      • Task Agent    — natural language task management
      • Router Agent  — auto-detects the right agent
      • Direct        — plain LLM conversation

    Pass agent_type="router" to let the system decide automatically.
    """
    start = time.perf_counter()

    # --- Resolve agent type ---
    agent_type_str = body.agent_type.lower()
    if agent_type_str == "router":
        resolved = await route_query(body.message)
        agent_type_str = resolved.value

    # --- Get or create conversation ---
    conversation = await _get_or_create_conversation(
        body.conversation_id, current_user.id, agent_type_str, db
    )

    # --- Load conversation history for context ---
    if body.conversation_id:
        history_result = await db.execute(
            select(Message)
            .where(Message.conversation_id == conversation.id)
            .order_by(Message.created_at)
        )
        history_messages = [
            {"role": m.role, "content": m.content}
            for m in history_result.scalars().all()
        ]
    else:
        history_messages = []

    sources: list = []
    tool_calls: list = []
    llm_resp: LLMResponse | None = None

    try:
        # --- Dispatch to agent ---
        if agent_type_str == AgentType.RAG:
            rag = RAGAgent()
            llm_resp, search_results = await rag.run(
                query=body.message,
                owner_id=current_user.id,
                conversation_history=history_messages,
                use_cache=not body.stream,
            )
            sources = search_results

        elif agent_type_str == AgentType.GMAIL:
            gmail = GmailAgent(user_id=current_user.id, db=db)
            # Simple routing within the Gmail agent
            message_lower = body.message.lower()
            if "send" in message_lower or "compose" in message_lower:
                # Extract params via LLM then send — simplified here
                content = "Please use the /gmail/send endpoint for sending emails."
                from app.services.llm.router import LLMResponse as LR
                from dataclasses import dataclass
                llm_resp_text = content
            else:
                llm_resp_text = await gmail.summarise_inbox()

            # Wrap in a synthetic LLMResponse
            from dataclasses import dataclass
            from app.services.llm.router import estimate_cost
            llm_resp = LLMResponse(
                content=llm_resp_text,
                provider=llm_router._cache.__class__.__name__,  # just a label
                model="gmail-agent",
                input_tokens=0,
                output_tokens=len(llm_resp_text.split()),
                latency_ms=(time.perf_counter() - start) * 1000,
            )
            # Override with real LLM router call
            llm_resp = await llm_router.complete(
                messages=[*history_messages, {"role": "user", "content": body.message}],
                system=f"You are a Gmail assistant. Context from Gmail: {llm_resp_text}",
            )

        elif agent_type_str == AgentType.TASK:
            task_agent = TaskAgent(user_id=current_user.id, db=db)
            response_text, tool_calls = await task_agent.run(
                instruction=body.message,
                context={"conversation_id": conversation.id},
            )
            llm_resp = await llm_router.complete(
                messages=[{"role": "user", "content": body.message}],
                system="You are a task management assistant. Summarise the result concisely.",
            )
            llm_resp.content = response_text  # Use task agent's response

        else:  # direct
            messages = [*history_messages, {"role": "user", "content": body.message}]
            llm_resp = await llm_router.complete(
                messages=messages,
                system="You are a helpful AI assistant.",
                use_cache=True,
            )

    except Exception as exc:
        logger.error("chat.error", error=str(exc), agent=agent_type_str)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Agent error: {str(exc)}",
        )

    # --- Persist to DB ---
    assistant_msg = await _save_messages(
        conversation=conversation,
        user_content=body.message,
        assistant_content=llm_resp.content,
        llm_resp=llm_resp,
        sources=sources,
        tool_calls=tool_calls,
        db=db,
    )
    await _log_agent_run(
        user_id=current_user.id,
        conversation_id=conversation.id,
        agent_type=agent_type_str,
        llm_resp=llm_resp,
        tool_calls=tool_calls,
        success=True,
        db=db,
    )

    logger.info(
        "chat.complete",
        user_id=current_user.id,
        agent=agent_type_str,
        latency_ms=round(llm_resp.latency_ms, 2),
        tokens=llm_resp.input_tokens + llm_resp.output_tokens,
        cached=llm_resp.was_cached,
    )

    source_chunks = [
        SourceChunk(
            document_id=s.document_id,
            chunk_id=s.weaviate_id,
            filename=s.filename,
            content=s.content,
            score=s.score,
        )
        for s in sources
    ] if body.include_sources else []

    return APIResponse(
        data=ChatResponse(
            conversation_id=conversation.id,
            message_id=assistant_msg.id,
            content=llm_resp.content,
            model_used=llm_resp.model,
            provider_used=llm_resp.provider,
            tokens_used=llm_resp.input_tokens + llm_resp.output_tokens,
            latency_ms=llm_resp.latency_ms,
            was_cached=llm_resp.was_cached,
            used_fallback=llm_resp.used_fallback,
            sources=source_chunks,
            tool_calls=tool_calls,
            created_at=assistant_msg.created_at,
        )
    )


