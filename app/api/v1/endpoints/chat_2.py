"""
app/api/v1/endpoints/chat.py
=============================
Chat endpoints — the primary user-facing AI interface.

  POST /chat           — send a message, get a response (supports all agents)
  POST /chat/stream    — SSE streaming response
  GET  /conversations  — list conversations
  GET  /conversations/{id} — get conversation with messages
  DELETE /conversations/{id} — archive/delete conversation

FLOW PER REQUEST:
  1. Authenticate user (JWT or API key)
  2. Route to correct agent (rag / gmail / task / router)
  3. Run agent → get LLMResponse + optional sources
  4. Persist conversation + message to PostgreSQL
  5. Write AgentRun metrics record
  6. Return ChatResponse

STREAMING:
  For streaming responses, we use Server-Sent Events (SSE).
  The client receives chunks as they're generated by the LLM.
  We flush the DB write after streaming is complete.
"""

