@router.get(
    "/conversations",
    response_model=APIResponse[PaginatedResponse],
    summary="List user conversations",
)
async def list_conversations(
    page: int = 1,
    page_size: int = 20,
    current_user: CurrentUser = ...,
    db: AsyncSession = Depends(get_db_session),
) -> APIResponse:
    from sqlalchemy import func

    offset = (page - 1) * page_size
    q = (
        select(Conversation)
        .where(Conversation.user_id == current_user.id)
        .where(Conversation.is_archived == False)  # noqa
        .order_by(Conversation.updated_at.desc())
        .offset(offset)
        .limit(page_size)
    )
    total_q = (
        select(func.count())
        .select_from(Conversation)
        .where(Conversation.user_id == current_user.id)
        .where(Conversation.is_archived == False)  # noqa
    )

    result = await db.execute(q)
    total = (await db.execute(total_q)).scalar_one()
    conversations = result.scalars().all()

    return APIResponse(
        data=PaginatedResponse(
            items=[
                {
                    "id": c.id, "title": c.title, "agent_type": c.agent_type,
                    "model_used": c.model_used, "total_tokens": c.total_tokens,
                    "total_cost_usd": c.total_cost_usd, "updated_at": c.updated_at.isoformat(),
                }
                for c in conversations
            ],
            total=total,
            page=page,
            page_size=page_size,
            pages=(total + page_size - 1) // page_size,
        )
    )


