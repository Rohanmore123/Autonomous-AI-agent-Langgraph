@router.get(
    "/conversations/{conversation_id}",
    summary="Get conversation with full message history",
)
async def get_conversation(
    conversation_id: str,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db_session),
) -> APIResponse:
    result = await db.execute(
        select(Conversation)
        .options(selectinload(Conversation.messages))
        .where(Conversation.id == conversation_id)
        .where(Conversation.user_id == current_user.id)
    )
    conv = result.scalar_one_or_none()
    if not conv:
        raise HTTPException(status_code=404, detail="Conversation not found")

    return APIResponse(
        data={
            "id": conv.id,
            "title": conv.title,
            "agent_type": conv.agent_type,
            "total_tokens": conv.total_tokens,
            "total_cost_usd": conv.total_cost_usd,
            "messages": [
                {
                    "id": m.id, "role": m.role, "content": m.content,
                    "model": m.model, "tokens_used": m.tokens_used,
                    "latency_ms": m.latency_ms, "sources": m.sources,
                    "tool_calls": m.tool_calls, "created_at": m.created_at.isoformat(),
                }
                for m in conv.messages
            ],
        }
    )


